"""
Write full-atom structures to PDB format.

Produces standard ATOM records compatible with PyMOL, VMD, ChimeraX, and
other molecular-visualization / analysis tools.
"""

from __future__ import annotations

import io
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Sequence, TextIO, Union

import numpy as np

from .constants import ONE_TO_THREE


# ── Atom data container ────────────────────────────────────────────────────

@dataclass
class FullAtom:
    """One atom ready for PDB output."""
    name: str                 # e.g. "CA", "CB", "OG1"
    residue_name: str         # 3-letter code, e.g. "ALA"
    residue_index: int        # 0-based (written as 1-based in PDB)
    position: np.ndarray      # (3,) xyz in angstroms
    chain_id: str = "A"
    element: str = ""         # auto-derived if empty
    occupancy: float = 1.0
    b_factor: float = 0.0


def _guess_element(atom_name: str) -> str:
    """Derive element symbol from PDB atom name."""
    name = atom_name.strip()
    if not name:
        return "X"
    # Standard backbone / common atoms
    if name in ("N", "NE", "NE1", "NE2", "ND1", "ND2", "NZ", "NH1", "NH2"):
        return "N"
    if name in ("O", "OG", "OG1", "OH", "OD1", "OD2", "OE1", "OE2", "OXT"):
        return "O"
    if name in ("S", "SD", "SG"):
        return "S"
    if name.startswith("C"):
        return "C"
    if name.startswith("N"):
        return "N"
    if name.startswith("O"):
        return "O"
    if name.startswith("S"):
        return "S"
    return name[0].upper()


# ── Backbone atom ordering (canonical PDB order) ──────────────────────────
_BACKBONE_ORDER = {"N": 0, "CA": 1, "C": 2, "O": 3, "CB": 4}


def _atom_sort_key(atom: FullAtom) -> tuple:
    """Sort atoms by residue, then backbone-first, then name."""
    bb = _BACKBONE_ORDER.get(atom.name, 100)
    return (atom.residue_index, bb, atom.name)


# ── PDB writer ─────────────────────────────────────────────────────────────

def _format_atom_name(name: str) -> str:
    """
    Format atom name for PDB ATOM record (columns 13-16).

    PDB convention: 1-letter element names start at column 14 (right-justified
    in a 4-char field), 2-letter element names start at column 13.
    """
    if len(name) >= 4:
        return name[:4]
    if len(name) == 1:
        return f" {name}  "
    if len(name) == 2:
        return f" {name} "
    # len == 3
    return f" {name}"


def write_pdb(
    atoms: Sequence[FullAtom],
    output: Union[str, Path, TextIO, None] = None,
    title: str = "QSAD CA2ALL RECONSTRUCTION",
    chain_id: str = "A",
) -> str:
    """
    Write a list of ``FullAtom`` to PDB format.

    Parameters
    ----------
    atoms   : atoms to write (will be sorted by residue / backbone order).
    output  : file path, writable stream, or None (return string).
    title   : TITLE record content.
    chain_id: override chain ID for all atoms.

    Returns
    -------
    The PDB-formatted string (always returned, also written if *output* given).
    """
    sorted_atoms = sorted(atoms, key=_atom_sort_key)

    lines: List[str] = []
    lines.append(f"HEADER    {title}")
    lines.append(f"TITLE     {title}")
    lines.append(f"REMARK    GENERATED BY QSAD POST_PROCESS.CA2ALL")

    serial = 1
    for atom in sorted_atoms:
        res_name = atom.residue_name
        res_seq = atom.residue_index + 1  # 1-based
        x, y, z = atom.position
        element = atom.element or _guess_element(atom.name)
        aname = _format_atom_name(atom.name)
        cid = chain_id or atom.chain_id

        # Standard PDB ATOM record (80 columns)
        line = (
            f"ATOM  {serial:5d} {aname}{' ':1s}"
            f"{res_name:>3s} {cid:1s}{res_seq:4d}    "
            f"{x:8.3f}{y:8.3f}{z:8.3f}"
            f"{atom.occupancy:6.2f}{atom.b_factor:6.2f}"
            f"          {element:>2s}  "
        )
        lines.append(line)
        serial += 1

    lines.append("TER")
    lines.append("END")

    pdb_text = "\n".join(lines) + "\n"

    if output is not None:
        if isinstance(output, (str, Path)):
            Path(output).parent.mkdir(parents=True, exist_ok=True)
            with open(output, "w") as fh:
                fh.write(pdb_text)
        else:
            output.write(pdb_text)

    return pdb_text


def atoms_from_reconstruction(
    backbone_atoms: list,
    sidechain_atoms: list,
    sequence: str,
    chain_id: str = "A",
) -> List[FullAtom]:
    """
    Merge backbone and sidechain atom lists into FullAtom objects.

    Parameters
    ----------
    backbone_atoms  : list of BackboneAtom from backbone.py
    sidechain_atoms : list of SidechainAtom from sidechain.py
    sequence        : 1-letter amino acid sequence
    chain_id        : PDB chain identifier

    Returns
    -------
    List of FullAtom ready for ``write_pdb()``.
    """
    seq = sequence.upper()
    result: List[FullAtom] = []

    for ba in backbone_atoms:
        res_idx = ba.residue_index
        res1 = seq[res_idx] if res_idx < len(seq) else "X"
        res3 = ONE_TO_THREE.get(res1, "UNK")
        result.append(FullAtom(
            name=ba.name,
            residue_name=res3,
            residue_index=res_idx,
            position=ba.position,
            chain_id=chain_id,
        ))

    for sa in sidechain_atoms:
        res_idx = sa.residue_index
        res1 = seq[res_idx] if res_idx < len(seq) else "X"
        res3 = ONE_TO_THREE.get(res1, "UNK")
        result.append(FullAtom(
            name=sa.name,
            residue_name=res3,
            residue_index=res_idx,
            position=sa.position,
            chain_id=chain_id,
        ))

    return result


